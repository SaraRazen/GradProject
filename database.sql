BEGIN;
CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(120) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,
 role VARCHAR(24) NOT NULL CHECK (role IN ('patient','physiotherapist','admin')),
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE exercises (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL UNIQUE,
 description TEXT,
 instructions TEXT,
 difficulty VARCHAR(20) CHECK (difficulty IN ('beginner','intermediate','advanced')),
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE assignments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 physiotherapist_id BIGINT NOT NULL REFERENCES users(id),
 patient_id BIGINT NOT NULL REFERENCES users(id),
 assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 ended_at TIMESTAMPTZ,
 status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','ended','pending')),
 CHECK (physiotherapist_id <> patient_id),
 CHECK (ended_at IS NULL OR ended_at >= assigned_at)
);
CREATE TABLE consents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id BIGINT NOT NULL REFERENCES users(id),
 physiotherapist_id BIGINT NOT NULL REFERENCES users(id),
 status VARCHAR(20) NOT NULL CHECK (status IN ('granted','revoked')),
 decided_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 notes TEXT,
 CHECK (patient_id <> physiotherapist_id)
);
CREATE TABLE sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id BIGINT NOT NULL REFERENCES users(id),
 started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 completed_at TIMESTAMPTZ,
 status VARCHAR(20) NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress','completed','cancelled')),
 notes TEXT,
 CHECK (completed_at IS NULL OR completed_at >= started_at),
 CHECK (status <> 'completed' OR completed_at IS NOT NULL)
);
CREATE TABLE session_results (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id BIGINT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
 exercise_id BIGINT NOT NULL REFERENCES exercises(id),
 repetitions INTEGER CHECK (repetitions IS NULL OR repetitions >= 0),
 duration_seconds INTEGER CHECK (duration_seconds IS NULL OR duration_seconds >= 0),
 score NUMERIC(5,2) CHECK (score IS NULL OR score BETWEEN 0 AND 100),
 pain_level SMALLINT CHECK (pain_level IS NULL OR pain_level BETWEEN 0 AND 10),
 notes TEXT,
 recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE body_tracking_points (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_result_id BIGINT NOT NULL REFERENCES session_results(id) ON DELETE CASCADE,
 captured_at TIMESTAMPTZ NOT NULL,
 body_point VARCHAR(80) NOT NULL,
 x NUMERIC(10,6),
 y NUMERIC(10,6),
 z NUMERIC(10,6),
 confidence NUMERIC(4,3) CHECK (confidence IS NULL OR confidence BETWEEN 0 AND 1)
);
CREATE INDEX idx_assignments_patient_status ON assignments(patient_id,status);
CREATE INDEX idx_assignments_physio_status ON assignments(physiotherapist_id,status);
CREATE INDEX idx_consents_patient_physio_time ON consents(patient_id,physiotherapist_id,decided_at DESC);
CREATE INDEX idx_sessions_patient_started ON sessions(patient_id,started_at DESC);
CREATE INDEX idx_session_results_session ON session_results(session_id);
CREATE INDEX idx_session_results_exercise ON session_results(exercise_id);
CREATE INDEX idx_body_tracking_result_time ON body_tracking_points(session_result_id,captured_at);
